#!/usr/bin/env bash
# Regenerate scripts/build/rail_data.lua from the game (tests/bezierio-test/scenarios/rail-data).
# Usage: tests/gen-rail-data.sh   (FACTORIO= as for run.sh)
set -euo pipefail
REPO="$(cd "$(dirname "$0")/.." && pwd)"
WORKDIR="$(mktemp -d)"
WORKDIR="$WORKDIR" "$REPO/tests/run.sh" rail-data "$@" > /dev/null
line="$(grep -o 'RAILDATA {.*' "$WORKDIR/stdout.log" | head -1)"
[[ -n "$line" ]] || { echo "no rail data in $WORKDIR/stdout.log"; exit 1; }
version="$(grep -o 'Factorio [0-9.]*' "$WORKDIR/stdout.log" | head -1 || true)"
out="${OUT:-$REPO/scripts/build/rail_data.lua}"
{
  echo "-- Generated by tests/gen-rail-data.sh from the game ($version): do not edit."
  echo "--"
  echo "-- ends[direction][parity of the end position]: the rail pieces the rail planner"
  echo "-- can attach at a rail end facing that way (entity name, position and direction"
  echo "-- relative to the end, and the new end it leads to), and the signal locations"
  echo "-- there. Rail ends face out of their rail; a piece attached at an end facing d"
  echo "-- has its other end ('goal') facing on along the track."
  echo "return ${line#RAILDATA }"
} > "$out"
echo "wrote $out"
